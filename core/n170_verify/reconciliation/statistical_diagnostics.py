"""Contextual, non-accusatory statistical diagnostics (GLM smoothing, tail profile, concentration)."""

from __future__ import annotations

from collections.abc import Sequence
import math

from n170_verify.contracts import PerformanceSummary, StatisticalDiagnostic
from n170_verify.performance.econometrics import (
    GLM_XI_THRESHOLD,
    compute_higher_moments,
    compute_sample_autocorrelation,
    estimate_glm_ma2,
)


def compute_top_k_positive_return_concentration(
    returns: Sequence[float],
    *,
    top_k: int = 3,
) -> float | None:
    """Compute share in ``[0.0, 1.0]`` of cumulative positive period returns generated by top ``top_k`` periods."""
    positives = sorted((float(r) for r in returns if math.isfinite(r) and r > 0.0), reverse=True)
    if not positives:
        return None
    total_pos = math.fsum(positives)
    if total_pos <= 1e-15:
        return None
    top_sum = math.fsum(positives[: max(1, top_k)])
    return min(1.0, max(0.0, top_sum / total_pos))


def build_statistical_diagnostics(
    *,
    period_returns: Sequence[float] = (),
    performance_summary: PerformanceSummary | None = None,
    periods_per_year: int = 252,
) -> list[StatisticalDiagnostic]:
    """Emit neutral econometric diagnostics (GLM xi, skewness/kurtosis, return concentration).

    Diagnostics carry descriptive econometric interpretations and explicit caveats only—never
    arbitrary numerical score cutoffs or accusatory labels.
    """
    xi: float | None = None
    rho1: float | None = None
    skew: float | None = None
    excess_kurt: float | None = None

    if performance_summary is not None:
        xi = performance_summary.smoothing_index_xi
        rho1 = performance_summary.lag1_autocorrelation
        skew = performance_summary.skewness
        excess_kurt = performance_summary.excess_kurtosis

    if period_returns:
        if skew is None and excess_kurt is None:
            skew, excess_kurt = compute_higher_moments(period_returns)
        if rho1 is None:
            rho1 = compute_sample_autocorrelation(period_returns, lag=1)
        if xi is None:
            glm = estimate_glm_ma2(period_returns, periods_per_year=float(periods_per_year))
            if glm is not None:
                xi = glm.smoothing_index_xi

    concentration = (
        compute_top_k_positive_return_concentration(period_returns, top_k=3)
        if period_returns
        else None
    )

    diagnostics: list[StatisticalDiagnostic] = []

    if xi is None:
        xi_interp = "Insufficient sub-period return observations to estimate Getmansky-Lo-Makarov (2004) MA(2) smoothing index."
    elif xi < GLM_XI_THRESHOLD:
        xi_interp = (
            f"GLM smoothing index xi={xi:.4f} (< {GLM_XI_THRESHOLD:.2f}) indicates positive multi-lag serial correlation, "
            "meaning raw volatility may understate multi-period economic volatility."
        )
    else:
        xi_interp = (
            f"GLM smoothing index xi={xi:.4f} is consistent with unsmoothed or low-autocorrelation daily marking."
        )

    diagnostics.append(
        StatisticalDiagnostic(
            metric_name="glm_smoothing_index_xi",
            observed_value=xi,
            interpretation=xi_interp,
            caveats=[
                "Serial correlation arises legitimately from trend-following strategies, illiquid option/OTC midpoints, or staggered global closes.",
                "Refer to unsmoothed_volatility and psr_glm_unsmoothed for autocorrelation-adjusted risk scaling.",
            ],
        )
    )

    if rho1 is None:
        rho_interp = "Insufficient observations to compute lag-1 return autocorrelation."
    else:
        rho_interp = f"Sample lag-1 return autocorrelation is {rho1:+.4f}."

    diagnostics.append(
        StatisticalDiagnostic(
            metric_name="lag1_return_autocorrelation",
            observed_value=rho1,
            interpretation=rho_interp,
            caveats=[
                "Finite-sample autocorrelation estimates exhibit substantial standard error of approximately 1/sqrt(T).",
            ],
        )
    )

    if skew is None:
        skew_interp = "Insufficient observations to compute sample return skewness."
    elif skew < -0.5:
        skew_interp = (
            f"Negative return skewness ({skew:+.4f}) indicates left-tail asymmetry typical of carry, credit, or short-volatility profiles."
        )
    elif skew > 0.5:
        skew_interp = (
            f"Positive return skewness ({skew:+.4f}) indicates right-tail asymmetry typical of convex, breakout, or long-option profiles."
        )
    else:
        skew_interp = f"Near-symmetric sample return skewness ({skew:+.4f})."

    diagnostics.append(
        StatisticalDiagnostic(
            metric_name="return_skewness",
            observed_value=skew,
            interpretation=skew_interp,
            caveats=[
                "Higher-moment estimates are sensitive to single catalyst days and sample horizon length.",
            ],
        )
    )

    if excess_kurt is None:
        kurt_interp = "Insufficient observations to compute sample excess kurtosis."
    elif excess_kurt > 1.0:
        kurt_interp = (
            f"Leptokurtic tail profile (excess kurtosis={excess_kurt:+.4f}) reflects heavier tails than a Gaussian benchmark."
        )
    else:
        kurt_interp = f"Sample excess kurtosis is {excess_kurt:+.4f} relative to a Gaussian normal distribution."

    diagnostics.append(
        StatisticalDiagnostic(
            metric_name="return_excess_kurtosis",
            observed_value=excess_kurt,
            interpretation=kurt_interp,
            caveats=[
                "Probabilistic Sharpe Ratio (PSR) explicitly incorporates skewness and excess kurtosis when T >= 30.",
            ],
        )
    )

    if concentration is None:
        conc_interp = "Return concentration could not be evaluated from available positive sub-periods."
    else:
        conc_interp = (
            f"Top 3 positive sub-periods account for {concentration * 100.0:.1f}% of gross positive sub-period returns."
        )

    diagnostics.append(
        StatisticalDiagnostic(
            metric_name="top_3_period_return_concentration",
            observed_value=concentration,
            interpretation=conc_interp,
            caveats=[
                "High return concentration is common in event-driven, earnings-catalyst, and asymmetric swing strategies.",
            ],
        )
    )

    return diagnostics


__all__ = [
    "build_statistical_diagnostics",
    "compute_top_k_positive_return_concentration",
]
